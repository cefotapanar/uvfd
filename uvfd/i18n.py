def set_lang(lang: str) -> None:
    global _lang
    _lang = "en" if lang == "en" else "mk"


def lang() -> str:
    return _lang


def tr(key: str, *args) -> str:
    pair = T.get(key)
    if pair is None:
        return key
    s = pair[0] if _lang == "mk" else pair[1]
    return s % args if args else s
