# -*- coding: utf-8 -*-
"""
Parameter catalog of the WSTG600 / SU650 family (resources/catalog.json,
generated by tools/build_catalog.py) plus the value formatting rules.

The raw 16-bit register value is always authoritative; the display value is
raw / 10**dec, read as signed where the parameter is flagged signed.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field

from .paths import resource

HEXD = "0123456789ABCDEF"
BASE_EEPROM = 0xF000     # read + persistent write
BASE_RAM = 0x0000        # write to RAM only (lost on power-off)


@dataclass
class Param:
    code: str
    g: int
    i: int
    name: str
    dec: int = 0
    unit: str = ""
    default: int | None = None
    flags: frozenset = field(default_factory=frozenset)
    range: str = ""
    options: list = field(default_factory=list)
    min: int | None = None
    max: int | None = None
    help: str = ""
    known: bool = True           # False = found on a drive, not in the manual

    @property
    def address(self) -> int:
        return BASE_EEPROM | (self.g << 8) | self.i

    @property
    def ram_address(self) -> int:
        return BASE_RAM | (self.g << 8) | self.i

    @property
    def ro(self) -> bool:
        return "ro" in self.flags

    @property
    def signed(self) -> bool:
        return "signed" in self.flags

    @property
    def stop_only(self) -> bool:
        return "stop" in self.flags

    @property
    def model_dep(self) -> bool:
        return "model" in self.flags

    @property
    def composite(self) -> bool:
        return "composite" in self.flags or "bits" in self.flags

    def option_text(self, raw: int | None) -> str:
        for n, label in self.options:
            if n == raw:
                return label
        return ""

    def fmt(self, raw: int | None, with_unit: bool = False) -> str:
        if raw is None:
            return ""
        if "bits" in self.flags:
            return "%04X" % (raw & 0xFFFF)
        v = to_signed(raw) if self.signed else raw
        s = fmt_num(v, self.dec)
        if with_unit and self.unit:
            s += " " + self.unit
        return s

    def parse(self, text: str) -> int:
        """Display text -> raw register value. Raises ValueError."""
        t = text.strip().replace(",", ".")
        if "bits" in self.flags:
            return int(t, 16) & 0xFFFF
        v = round(float(t) * 10 ** self.dec)
        if v < 0:
            if v < -32768:
                raise ValueError("too small")
            return v & 0xFFFF
        if v > 65535:
            raise ValueError("too large")
        return v

    def matches(self, q: str) -> bool:
        q = q.lower().strip()
        if not q:
            return True
        hay = " ".join([self.code, self.code.replace("-", ""), self.name, self.range,
                        self.help, " ".join(o[1] for o in self.options)]).lower()
        return all(part in hay for part in q.split())


def to_signed(v: int) -> int:
    return v - 65536 if v > 32767 else v


def fmt_num(v: float | int | None, dec: int) -> str:
    if v is None:
        return ""
    if dec <= 0:
        return str(int(v))
    return ("%." + str(dec) + "f") % (v / (10.0 ** dec))


def make_code(g: int, i: int) -> str:
    return "P%s-%02d" % (HEXD[g], i)


def parse_code(s: str):
    """'P0-10' / 'p010' / 'P0.10' -> (0, 10); None if it is not a code."""
    m = re.fullmatch(r"\s*[Pp]([0-9A-Fa-f])\s*[-.]?\s*(\d{1,3})\s*", s or "")
    if not m:
        return None
    i = int(m.group(2))
    return (HEXD.index(m.group(1).upper()), i) if i <= 255 else None


@dataclass
class Group:
    id: str
    g: int
    mk: str
    en: str
    count: int
    max_index: int

    def title(self, lang: str) -> str:
        return self.mk if lang == "mk" else self.en


class Catalog:
    def __init__(self, data: dict):
        self.family = data.get("family", "")
        self.groups = [Group(**{k: v for k, v in g.items()}) for g in data["groups"]]
        self.params: list[Param] = []
        self.by_code: dict[str, Param] = {}
        for p in data["params"]:
            self._add(Param(code=p["code"], g=p["g"], i=p["i"], name=p["name"], dec=p["dec"],
                            unit=p.get("unit", ""), default=p.get("default"),
                            flags=frozenset(p.get("flags", [])), range=p.get("range", ""),
                            options=[list(o) for o in p.get("options", [])],
                            min=p.get("min"), max=p.get("max"), help=p.get("help", "")))

    def _add(self, p: Param):
        self.params.append(p)
        self.by_code[p.code] = p

    @classmethod
    def load(cls) -> "Catalog":
        with open(resource("catalog.json"), encoding="utf-8") as f:
            return cls(json.load(f))

    def get(self, code: str) -> Param | None:
        return self.by_code.get(code)

    def group(self, g: int) -> list[Param]:
        return [p for p in self.params if p.g == g]

    def ensure(self, code: str) -> Param:
        """A code the drive has but the manual does not - add it as unknown."""
        p = self.by_code.get(code)
        if p is None:
            gi = parse_code(code)
            p = Param(code=code, g=gi[0], i=gi[1], name=code, known=False)
            self._add(p)
            self.params.sort(key=lambda x: (x.g, x.i))
        return p

    def group_title(self, g: int, lang: str) -> str:
        for grp in self.groups:
            if grp.g == g:
                return grp.title(lang)
        return "P" + HEXD[g]


# Write order: P0-10 (maximum frequency) first, then the limits, then the
# motor group, then the rest - the ranges depend on each other.
def write_rank(p: Param) -> tuple:
    if p.g == 0 and p.i == 10:
        r = 0
    elif p.g == 0 and p.i in (12, 14):
        r = 1
    elif p.g == 1:
        r = 2
    else:
        r = 3
    return (r, p.g, p.i)
