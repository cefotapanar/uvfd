# -*- coding: utf-8 -*-
"""
Builds uvfd/resources/models.json - every inverter model of the two manuals
(power, input/output current, supply), used to name a drive that has lost
its nameplate.

    python tools/build_models.py [--manual PDF]

Sources: WSTG600 manual Table 2-1 (G600 series) and the SU-650 manual 1.3.
Where the G600 table prints a kW that contradicts the model's own name
(6T18.5GB "18", 6T30G "37", 6T560G "500") the name wins - the name is what
is on the housing.
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "uvfd" / "resources" / "models.json"
DEF_MANUAL = Path(r"C:\Users\cefot\Desktop\Stvari\AI\UPATSTVA\VFD\WSTG600\WSTG600 inverter user manual.pdf")

SUPPLY = {"1AC 220": "1AC 220 V", "3AC 220": "3AC 220 V", "3AC 380": "3AC 380 V", "3AC480": "3AC 690 V"}

# SU-650 manual 1.3 (single-phase 220 V in): model, kVA, input A, output A, kW
SU650 = [("650-0R75-G2", 1.5, 8.2, 4.0, 0.75), ("650-1R5-G2", 3.0, 14.0, 7.0, 1.5),
         ("650-2R2-G2", 4.0, 23.0, 9.6, 2.2)]


def num(s: str):
    try:
        return float(s)
    except ValueError:
        return None


def name_kw(model: str):
    m = re.search(r"[0-9][ST]([0-9.]+)G", model)
    if not m:
        return None
    v = float(m.group(1))
    return 0.75 if v == 0.7 else v


def g600(pdf: Path) -> list[dict]:
    import fitz
    text = "\n".join(p.get_text() for p in fitz.open(str(pdf)))
    i = text.find("Table 2-1 G600 Series Inverter Model")
    j = text.find("2.6 Technical Specifications", i)
    toks = [t.strip() for t in text[i:j].splitlines() if t.strip()]
    out, supply, k = [], "", 0
    while k < len(toks):
        t = toks[k]
        hit = next((v for key, v in SUPPLY.items() if t.replace(" ", "").startswith(key.replace(" ", ""))), None)
        if hit:
            supply = hit
            k += 1
            continue
        if re.fullmatch(r"G600-[0-9][ST][0-9.]+GB?", t) and k + 4 < len(toks):
            kw, hp, ia, oa = toks[k + 1:k + 5]
            g = lambda s, n: num(s.split("/")[n]) if "/" in s or n == 0 else None  # noqa: E731
            entry = {"series": "Winston G600 / WSTG600", "model": t, "supply": supply,
                     "kw": g(kw, 0), "in_a": g(ia, 0), "out_a": g(oa, 0)}
            if "/" in kw:                                        # G / P rating
                entry.update(kw_p=g(kw, 1), in_a_p=g(ia, 1), out_a_p=g(oa, 1))
            nk = name_kw(t)
            if nk is not None and entry["kw"] != nk:
                entry["kw"] = nk
            out.append(entry)
            k += 5
            continue
        k += 1
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--manual", type=Path, default=DEF_MANUAL)
    a = ap.parse_args()
    models = g600(a.manual)
    for model, kva, ia, oa, kw in SU650:
        models.append({"series": "SUSWE SU650", "model": model, "supply": "1AC 220 V", "kw": kw,
                       "in_a": ia, "out_a": oa, "kva": kva})
    OUT.write_text(json.dumps({"schema": "uvfd-models/1", "note": "Generated by tools/build_models.py",
                               "models": models}, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print("%d models -> %s" % (len(models), OUT))


if __name__ == "__main__":
    main()
